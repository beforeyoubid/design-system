#!/usr/bin/env node
/**
 * Generates everything that's derived from the token files:
 *   - src/tokens/components/index.css   imports every token file
 *   - console/src/generated/manifest.json   brand, semantic and component tokens for the Design Console (not committed)
 *   - the "Component tokens" table in DESIGN.md (between the component-tokens markers)
 *
 *   node scripts/tokens/build.mjs           write them
 *   node scripts/tokens/build.mjs --check   fail if any is out of date
 */
import fs from 'node:fs'
import path from 'node:path'
import { findSites, parseTokenFile, parseTokenName, root, tokenDir, tokenFiles, uiDir, valueType, STATES, PROPERTIES } from './lib.mjs'
import { resolveColor, rootVars, toHex } from './color.mjs'

const check = process.argv.includes('--check')
const outputs = []

// ---------- index.css ----------
// Every token file, compiled into one stylesheet. Each rule's selector is widened
// from [data-slot="x"] to also match any element whose classes read x's tokens:
// when a part renders another (<DialogTrigger render={<Button />}>), Base UI keeps
// the outer data-slot, but the button's classes still need the button's tokens.
const files = tokenFiles()
const compiled = files.map(({ component, file }) => {
  const css = fs.readFileSync(file, 'utf8')
  return `/* ---- ${component}.css ---- */\n` + css.replace(/^\[data-slot="([\w-]+)"\]\s*\{/gm, (_, slot) =>
    `[data-slot="${slot}"],\n[class*="(--_${slot}-"],\n[class*="(--_${slot})"] {`)
})
outputs.push({
  file: path.join(tokenDir, 'index.css'),
  content: `/* Component tokens. Generated by scripts/tokens/build.mjs from the files in this folder; don't edit. */\n\n${compiled.join('\n')}`,
})

// ---------- manifest ----------
const uiSources = fs.readdirSync(uiDir).filter((f) => f.endsWith('.tsx')).map((f) => fs.readFileSync(path.join(uiDir, f), 'utf8'))
// The file that defines the part's cva wins over one that only passes its data-slot.
const keysFor = (slot) => {
  for (const src of uiSources) {
    const { slots, cvas } = findSites(src)
    const c = slots.get(slot)?.cva
    if (c) return [...(cvas.get(c)?.keys.keys() ?? [])]
  }
  return []
}
const refs = (value) => [...value.matchAll(/var\((--(?:[\w-]|\\:)+)/g)].map((m) => m[1])

const components = files.map(({ component, file }) => {
  const { header, rules } = parseTokenFile(file)
  const tokens = []
  for (const rule of rules) {
    const keys = keysFor(rule.slot)
    for (const t of rule.tokens) {
      const p = parseTokenName(t, rule, keys)
      tokens.push({
        name: t.public,
        private: t.name,
        default: t.fallback,
        description: t.description,
        type: valueType(p.property),
        part: rule.slot,
        // An @ours variant isn't a cva key; it keeps its name.
        variant: p.variant?.key ?? p.variant?.unresolved ?? null,
        state: p.state,
        property: p.property || 'fill',
        reads: refs(t.fallback),
        on: t.on,
      })
    }
  }
  return { component, description: header, tokens }
})

// Brand tokens: colour primitives (with hex), radius, type scale. Semantic tokens: shadcn roles.
const css = fs.readFileSync(path.join(root, 'globals.css'), 'utf8')
const firstRoot = css.match(/(?:^|\n):root\s*\{([\s\S]*?)\n\}/)[1]
const brandColors = [...firstRoot.matchAll(/(--(?:[\w-]|\\:)+):\s*oklch\([^)]*\);\s*\/\*\s*(#[0-9A-Fa-f]{6})/g)].map(([, name, hex]) => ({ name, hex: hex.toUpperCase() }))
const scale = (re) => [...firstRoot.matchAll(re)].map(([, name, value]) => ({ name, value: value.trim() }))
const radius = scale(/(--radius-[\w]+):\s*([^;]+);/g)
const text = scale(/(--text-[\w-]+?):\s*([^;]+);/g).filter((t) => !t.name.includes('--', 2))
const SEMANTIC = [
  'background', 'foreground', 'card', 'card-foreground', 'popover', 'popover-foreground', 'primary', 'primary-foreground',
  'secondary', 'secondary-foreground', 'muted', 'muted-foreground', 'accent', 'accent-foreground', 'destructive',
  'destructive-foreground', 'success', 'success-foreground', 'warning', 'warning-foreground', 'border', 'input', 'ring',
]
const semantic = SEMANTIC.filter((n) => rootVars.has(`--${n}`)).map((n) => {
  const value = rootVars.get(`--${n}`)
  const c = resolveColor(value)
  // Components that read it: via a component token's default, or a class like bg-accent in a ui file.
  const viaTokens = components.filter((c2) => c2.tokens.some((t) => t.reads.includes(`--${n}`))).map((c2) => c2.component)
  const classRe = new RegExp(`(?:^|[\\s:"'])(?:bg|text|border|ring|outline|fill|stroke|from|to|via)-${n}(?:/\\d+)?(?=[\\s"'])`)
  const viaClasses = fs.readdirSync(uiDir).filter((f) => classRe.test(fs.readFileSync(path.join(uiDir, f), 'utf8'))).map((f) => f.replace('.tsx', ''))
  return { name: `--${n}`, value, hex: c ? toHex(c) : null, usedBy: [...new Set([...viaTokens, ...viaClasses])].sort() }
})

const manifest = {
  generated: 'scripts/tokens/build.mjs',
  brand: { colors: brandColors, radius, text, spacing: rootVars.get('--spacing') ?? '0.25rem' },
  semantic,
  components,
  states: Object.fromEntries(Object.entries(STATES).map(([k, v]) => [k, v.label])),
  properties: Object.fromEntries(Object.entries(PROPERTIES).map(([k, v]) => [k || 'fill', { label: v.label, type: v.type }])),
  // Pairs under AA that are known: the console shows the note next to the result.
  contrastExceptions: JSON.parse(fs.readFileSync(path.join(root, 'scripts', 'tokens', 'contrast-exceptions.json'), 'utf8')),
}
// Not committed: the console builds it before it starts, so --check skips it.
outputs.push({ file: path.join(root, 'console', 'src', 'generated', 'manifest.json'), content: JSON.stringify(manifest, null, 1) + '\n', untracked: true })

// ---------- DESIGN.md table ----------
const designFile = path.join(root, 'DESIGN.md')
const design = fs.readFileSync(designFile, 'utf8')
const start = '<!-- component-tokens:start -->'
const end = '<!-- component-tokens:end -->'
if (design.includes(start)) {
  const rows = components
    .map((c) => {
      // One collapsed block per component: 800 rows open at once would bury the rest of the doc.
      const cell = (v) => v.replace(/\|/g, '\\|')
      const lines = c.tokens.map((t) => `| \`${t.name}\` | ${cell(t.description)} | \`${cell(t.default)}\` |`)
      return `<details>\n<summary><strong>${c.component}</strong> (${c.tokens.length})</summary>\n\n| Component token | What it changes | Default |\n|---|---|---|\n${lines.join('\n')}\n\n</details>\n`
    })
    .join('\n')
  const table = `${start}\n<!-- Generated by scripts/tokens/build.mjs from src/tokens/components/*.css; don't edit. -->\n\n${rows}\n${end}`
  outputs.push({ file: designFile, content: design.replace(new RegExp(`${start}[\\s\\S]*?${end}`), table) })
}

// ---------- write or check ----------
const stale = outputs.filter(({ file, content, untracked }) => !(check && untracked) && (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content))
if (check) {
  if (stale.length) {
    console.error(`✖ Out of date (run node scripts/tokens/build.mjs):\n  ${stale.map((o) => path.relative(root, o.file)).join('\n  ')}`)
    process.exit(1)
  }
  console.log('✅ Generated token outputs are up to date.')
} else {
  for (const { file, content } of stale) {
    fs.mkdirSync(path.dirname(file), { recursive: true })
    fs.writeFileSync(file, content)
  }
  console.log(stale.length ? `Wrote ${stale.map((o) => path.relative(root, o.file)).join(', ')}` : 'Already up to date.')
}
